const DICTS: Record<Lang, Dict> = { ru, uz };

export const LANGS: Array<{ code: Lang; label: string; short: string }> = [
  { code: "ru", label: "Русский", short: "RU" },
  { code: "uz", label: "O'zbekcha", short: "UZ" },
];

type Ctx = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
};

const I18nContext = createContext<Ctx | null>(null);

const STORAGE_KEY = "osh.lang";

function isLang(v: unknown): v is Lang {
  return v === "ru" || v === "uz";
}

function readInitial(): Lang {
  if (typeof window === "undefined") return "uz";
  const stored = window.localStorage.getItem(STORAGE_KEY);
  if (isLang(stored)) return stored;
  const nav = window.navigator?.language?.slice(0, 2);
  if (nav === "ru") return "ru";
  return "uz";
}

export function interpolate(s: string, vars?: Record<string, string | number>) {
  if (!vars) return s;
  let out = s;
  for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, String(v));
  return out;
}

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>) {
  const dict = DICTS[lang] ?? ru;
  return interpolate(dict[key] ?? uz[key] ?? ru[key] ?? base[key] ?? key, vars);
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("uz");

  useEffect(() => {
    const initial = readInitial();
    setLangState(initial);
    setMoneyLang(initial);
  }, []);

  useEffect(() => {
    setMoneyLang(lang);
    if (typeof document !== "undefined") document.documentElement.lang = lang;
  }, [lang]);

  const value = useMemo<Ctx>(
    () => ({
      lang,
      setLang: (l) => {
        setLangState(l);
        setMoneyLang(l);
        try {
          window.localStorage.setItem(STORAGE_KEY, l);
        } catch {
          /* private mode */
        }
      },
      t: (key, vars) => translate(lang, key, vars),
    }),
    [lang],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useT() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useT must be inside <I18nProvider>");
  return ctx;
}

/** Sync local language with the profile row (called from provider consumer). */
export function useSyncLangFromProfile(profileLang: Lang | null | undefined) {
  const { lang, setLang } = useT();
  const qc = useQueryClient();
  useEffect(() => {
    if (profileLang && isLang(profileLang) && profileLang !== lang) {
      setLang(profileLang);
      qc.invalidateQueries();
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [profileLang]);
}

